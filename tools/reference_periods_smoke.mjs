import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(pathToFileURL(path.join(os.homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs')).href);
const references = JSON.parse(await readFile('config/matrix_references.json', 'utf8'));
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
const library = () => page.evaluate(() => localStorage.getItem('wuwa-matrix-plan-library-v1'));
try {
  await mkdir('outputs', { recursive: true });
  await page.goto(process.env.MATRIX_URL || 'http://127.0.0.1:4173');
  await page.locator('.team-bar').first().waitFor();
  assert.equal(await page.locator('#stamina-season option').count(), 9);
  assert.equal(await page.locator('#plan-season option').count(), 2);
  const original = await library();
  const bars = await page.locator('.team-bar').evaluateAll(nodes => nodes.map(node => [node.dataset.id, node.style.left, node.style.width]));
  const bosses = await page.locator('.boss-name').allTextContents();
  for (const period of references.periods.filter(period => period.viewOnly)) {
    await page.locator('#stamina-season').selectOption(period.id);
    assert.equal(await page.locator('#stamina-season').inputValue(), period.id);
    assert.match(await page.locator('#matrix-details-title').innerText(), /仅查看/);
    assert.ok((await page.locator('#matrix-details-title').innerText()).includes(period.name));
    assert.deepEqual(await page.locator('.matrix-circuit p').allTextContents(), period.circuits.map(circuit => circuit.description));
    assert.equal(await page.locator('#circuit-buffs').evaluate(node => node.open), true);
    await page.locator('.matrix-circuit-icon').evaluateAll(images => Promise.all(images.map(image => image.decode())));
    assert.equal(await page.locator('#matrix-character-heading').isVisible(), false);
    assert.match(await page.locator('#stamina-season-note').innerText(), /体力仍按.*S2-3/);
    assert.equal(await library(), original);
    assert.deepEqual(await page.locator('.boss-name').allTextContents(), bosses);
    assert.deepEqual(await page.locator('.team-bar').evaluateAll(nodes => nodes.map(node => [node.dataset.id, node.style.left, node.style.width])), bars);
  }
  await page.locator('#stamina-season').selectOption('s0-phase1');
  await page.locator('#matrix-details').screenshot({ path: 'outputs/v033-s0-circuits.png' });
  const downloadEvent = page.waitForEvent('download'); await page.locator('#export-season-config').click();
  const download = await downloadEvent; await download.saveAs('outputs/v033-reference-export.json');
  assert.deepEqual(JSON.parse(await readFile('outputs/v033-reference-export.json', 'utf8')), references.periods[0]);
  assert.match(download.suggestedFilename(), /回路增益/);
  await page.locator('#quick-team').click();
  assert.match(await page.locator('.picker-stamina-note').innerText(), /S2-3.*琳奈/);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#stamina-season').inputValue(), 's0-phase1');
  await page.locator('#stamina-season').selectOption('s2-phase4');
  assert.match(await page.locator('#matrix-details-title').innerText(), /S2-4/);
  assert.deepEqual(await page.locator('.matrix-circuit p').allTextContents(), references.periods.at(-1).circuits.map(circuit => circuit.description));
  assert.equal(await page.locator('#matrix-character-heading').isVisible(), true);
  assert.match(await page.locator('#matrix-stamina-enhancements').innerText(), /洛瑟菈/);
  assert.deepEqual(await page.locator('.boss-name').allTextContents(), bosses);
  await page.locator('#new-plan').click();
  assert.deepEqual(await page.locator('#plan-season option').evaluateAll(nodes => nodes.map(node => node.value)), ['s2-phase3','s2-phase4']);
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#stamina-season').selectOption('s0-phase2');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  assert.equal(await page.locator('.matrix-circuit').count(), 4);
  await page.reload(); await page.locator('.team-bar').first().waitFor();
  assert.equal(await page.locator('#stamina-season').inputValue(), 's2-phase4');
  assert.deepEqual(errors, []);
  console.log('PASS: all nine circuit periods, seven read-only historical views, unchanged teams/scores/stamina/axis, reference export, two-only new-plan choices, current bonuses and mobile.');
} finally { await browser.close(); }
